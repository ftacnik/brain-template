#!/bin/bash
# Installs thin global wrappers for the brain's skills into ~/.claude/skills, so that
# /ask, /capture, /prep, /learn (and the rest) work from any Claude Code session and
# always operate on ~/brain. Re-run after changing a skill's description. Idempotent.
BRAIN="${BRAIN:-$HOME/brain}"   # set BRAIN=/other/path if your brain lives elsewhere
DEST="$HOME/.claude/skills"
for dir in "$BRAIN"/.claude/skills/*/; do
  name=$(basename "$dir")
  src="$dir/SKILL.md"
  [ -f "$src" ] || continue
  desc=$(awk '/^description:/{sub(/^description: */,""); print; exit}' "$src")
  mkdir -p "$DEST/$name"
  cat > "$DEST/$name/SKILL.md" <<WRAP
---
name: $name
description: $desc
---

# /$name (global wrapper)

This skill lives in the owner's second brain. Work in \`$BRAIN\`: run shell commands from there and use absolute paths for file tools. If you have not read \`$BRAIN/CLAUDE.md\` in this session, read it first. Then follow \`$BRAIN/.claude/skills/$name/SKILL.md\` exactly, resolving every relative path against \`$BRAIN\`. Inside the brain folder itself the project copy of this skill takes over.

Generated by \`~/brain/scripts/install-skills.sh\`. Do not edit here; edit the brain's copy and re-run the script.
WRAP
  echo "installed ~/.claude/skills/$name"
done
